class BaseAgent(ABC):
    """Abstract base agent class."""

    def __init__(self, agent_id: str, name: str, title: str, role: str, avatar: str, color: str):
        self.agent_id = agent_id
        self.name = name
        self.title = title
        self.role = role
        self.avatar = avatar
        self.color = color
        self.logs: List[Dict[str, Any]] = []

    def log(self, message: str, stage: str, data: Optional[Dict[str, Any]] = None):
        entry = {
            "timestamp": datetime.utcnow().isoformat() + "Z",
            "agent_id": self.agent_id,
            "agent_name": self.name,
            "stage": stage,
            "message": message,
            "data": data or {}
        }
        self.logs.append(entry)
        return entry

    def verify_quote(self, text: str, quote: str) -> bool:
        """Helper to ensure exact substring match without hallucinations."""
        if not quote or not text:
            return False
        clean_text = " ".join(text.split())
        clean_quote = " ".join(quote.split())
        return clean_quote.lower() in clean_text.lower()
