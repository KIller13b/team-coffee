"""
Base definitions, data models, and abstractions for the Odin Multi-Agent War Room.
"""

from abc import ABC, abstractmethod
from typing import List, Dict, Any, Optional, Literal
from pydantic import BaseModel, Field
from datetime import datetime


class Citation(BaseModel):
    """Grounding citation complying with the competition format specification."""
    doc_id: str = Field(description="Document ID without extension (e.g. 'STD', 'A1', 'B1')")
    clause: str = Field(description="Section heading or number (e.g. '§3.1', 'Section 14.2')")
    verbatim_quote: str = Field(description="Exact substring from canonical .txt contract file")
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)
    verified: bool = Field(default=True, description="Whether verbatim quote was verified in source text")


class ExtractedClause(BaseModel):
    id: str
    doc_id: str
    field: str
    extracted_value: str
    clause_citation: str
    verbatim_text: str
    category: str
    confidence_score: float = 0.95
    interpretation_note: Optional[str] = None
    is_ambiguous: bool = False
    ambiguity_reason: Optional[str] = None
    ambiguity_status: Optional[str] = None


class ExtractedObligation(BaseModel):
    id: str
    contract_id: str
    title: str
    description: str
    due_date: Optional[str] = None
    frequency: Optional[str] = None
    severity: Literal['low', 'medium', 'high', 'critical'] = 'medium'
    responsible_party: Literal['internal', 'counterparty', 'shared'] = 'counterparty'
    clause_reference: str
    financial_exposure_inr: float = 0.0


class ThorOutput(BaseModel):
    """Output from Thor: 'What does it say?'"""
    contract_id: str
    title: str
    counterparty: str
    clauses: List[ExtractedClause] = []
    obligations: List[ExtractedObligation] = []
    sla_thresholds: Dict[str, Any] = {}
    governing_law: Optional[str] = None
    notice_requirements: Optional[Dict[str, Any]] = None
    verbatim_citations: List[Citation] = []
    summary: str = ""


