import React from 'react'
import { Drawer } from '../../components/ui/Drawer'
import { Badge } from '../../components/ui/Badge'
import { ProgressBar } from '../../components/ui/ProgressBar'
import { ContractClause } from '../../types/contract'
import { formatConfidence } from '../../lib/formatters'
import { Quote, CheckCircle2, ShieldAlert } from 'lucide-react'

interface ClauseDetailDrawerProps {
  clause: ContractClause | null
  onClose: () => void
}

export const ClauseDetailDrawer: React.FC<ClauseDetailDrawerProps> = ({ clause, onClose }) => {
  if (!clause) return null

  const titleText = clause.field || (clause as any).title || 'Extracted Covenant'
  const citationText = clause.clauseCitation || (clause as any).section || 'Referenced Section'
  const valueText = clause.extractedValue || (clause as any).text || (clause as any).title || 'Extracted Term'
  const verbatimEvidence = clause.verbatimText || (clause as any).text || 'No verbatim excerpt recorded.'

  return (
    <Drawer
      isOpen={Boolean(clause)}
      onClose={onClose}
      title={titleText}
      subtitle={citationText}
      width="lg"
    >
      <div className="space-y-6">
        {/* Confidence & Extracted Value Card */}
        <div className="p-4 rounded-xl bg-[#10263B] border border-[#1D344B] space-y-3">
          <div className="flex items-center justify-between">
            <span className="text-[10px] uppercase font-bold text-[#64748B]">
              Extracted Legal Term
            </span>
            <div className="flex items-center gap-2">
              <span className="text-xs text-[#94A3B8]">Extraction Confidence:</span>
              <Badge variant="teal" size="xs">
                {formatConfidence(clause.confidenceScore)}
              </Badge>
            </div>
          </div>

          <h3 className="text-base font-bold text-[#F1F5F9] leading-snug">
            {valueText}
          </h3>

          <ProgressBar
            value={clause.confidenceScore * 100}
            color="teal"
            size="xs"
          />
        </div>

        {/* Verbatim Supporting Evidence (Anchor) */}
        <div>
          <div className="flex items-center justify-between mb-2">
            <h4 className="text-xs font-semibold uppercase tracking-wider text-teal-300 flex items-center gap-1.5">
              <Quote className="w-3.5 h-3.5 text-teal-400" />
              Verbatim Contract Evidence (OCR Anchor)
            </h4>
            <span className="text-[10px] text-[#94A3B8] font-mono">
              Anchored by Thor
            </span>
          </div>

          <div className="p-4 rounded-xl bg-[#081727] border border-teal-500/30 text-xs text-[#F1F5F9] font-mono leading-relaxed relative">
            <div className="absolute top-2 right-2 text-[10px] uppercase font-bold bg-teal-500/10 text-teal-300 px-1.5 py-0.5 rounded border border-teal-500/20">
              Verified Source
            </div>
            "{verbatimEvidence}"
          </div>
          <p className="text-[11px] text-[#64748B] mt-1.5">
            Verified citation location: <strong className="text-[#94A3B8]">{citationText}</strong>
          </p>
        </div>

        {/* AI-Generated Interpretation Note */}
        {clause.interpretationNote && (
          <div>
            <div className="flex items-center gap-1.5 mb-2">
              <ShieldAlert className="w-3.5 h-3.5 text-amber-400" />
              <h4 className="text-xs font-semibold uppercase tracking-wider text-amber-300">
                Agentic Risk Interpretation Note
              </h4>
              <span className="text-[10px] font-mono text-amber-400 bg-amber-500/10 px-1.5 py-0.2 rounded border border-amber-500/20 ml-auto">
                Loki / Norns Synthesis
              </span>
            </div>
            <div className="p-3.5 rounded-xl bg-amber-500/5 border border-amber-500/20 text-xs text-[#F1F5F9] leading-relaxed">
              {clause.interpretationNote}
            </div>
            <p className="text-[10.5px] text-[#64748B] mt-1 italic">
              Note: AI interpretation generated by multi-agent consensus. Not formal legal advice.
            </p>
          </div>
        )}

        {/* Metadata Grid */}
        <div className="grid grid-cols-2 gap-3 pt-2 border-t border-[#1D344B]">
          <div className="p-3 rounded-lg bg-[#0D2033] border border-[#1D344B]/70">
            <span className="text-[10px] text-[#64748B] uppercase font-bold block mb-1">
              Category
            </span>
            <span className="text-xs font-medium text-[#F1F5F9] capitalize">
              {clause.category}
            </span>
          </div>
          <div className="p-3 rounded-lg bg-[#0D2033] border border-[#1D344B]/70">
            <span className="text-[10px] text-[#64748B] uppercase font-bold block mb-1">
              Extraction Agent
            </span>
            <span className="text-xs font-medium text-teal-300 capitalize flex items-center gap-1">
              <CheckCircle2 className="w-3.5 h-3.5" />
              Agent {clause.extractedBy.toUpperCase()}
            </span>
          </div>
        </div>
      </div>
    </Drawer>
  )
}
